fn rng(stream: u64) -> CryptoRng {
    CryptoRng::new(&Secret::new(bytes::copy_of(&[0; 32])), stream).expect("32 bytes")
}
#[test]
fn a_zero_seed_on_stream_zero_gives_rfc_8439_vector_one() {
    let mut block = [0_u8; 64];
    rng(0).fill(&mut block);
    assert_eq!(block, ONE);
}
#[test]
fn the_stream_number_is_the_nonce_as_rfc_8439_vector_five_shows() {
    let mut block = [0_u8; 64];
    rng(2_u64 << 56_u32).fill(&mut block);
    assert_eq!(block, FIVE);
}
#[test]
fn the_second_block_follows_as_rfc_8439_vector_two_shows() {
    let mut random = rng(0);
    let mut block = [0_u8; 64];
    random.fill(&mut block);
    random.fill(&mut block);
    assert_eq!(block, TWO);
}
#[test]
fn fills_in_pieces_across_blocks_give_the_same_bytes() {
    let mut random = rng(0);
    let mut bytes = [0_u8; 128];
    for piece in bytes.chunks_mut(7) {
        random.fill(piece);
    }
    assert_eq!(&bytes[..64], &ONE);
    assert_eq!(&bytes[64..], &TWO);
}
#[test]
fn two_streams_of_one_seed_start_with_different_blocks() {
    let mut one = [0_u8; 64];
    let mut two = [0_u8; 64];
    rng(0).fill(&mut one);
    rng(1).fill(&mut two);
    assert_ne!(one, two);
}
#[test]
fn a_seed_that_is_not_32_bytes_makes_no_generator() {
    for length in [0, 31, 33] {
        assert!(CryptoRng::new(&Secret::new(bytes::zeroed(length)), 0).is_none());
    }
}
#[test]
fn debug_shows_only_the_stream_number() {
    assert_eq!(alloc::fmt::format(format_args!("{:?}", rng(7))), "CryptoRng { stream: 7 }");
}
