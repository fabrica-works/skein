pub fn written(site: Site, old: &Old, new: &mut Build, at: Node, cx: &mut Context) -> Result<(), Halt> {
    match site.patch() {
        1 => match site.index() {
            0 => p0001::shape(old, new, at, cx),
            1 => p0001::every_score(old, new, at, cx),
            _ => Err(Halt::NoSite(site)),
        },
        _ => Err(Halt::NoSite(site)),
    }
}

