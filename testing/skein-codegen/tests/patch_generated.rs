    #[test]
    fn baseline_dispatch_only_reports_the_missing_site() {
        let root = scratch("baseline");
        put(&root, "schema/kept/type-v1.schema", OTHER);
        assert_eq!(module::module(&root).expect("baseline module"), NO_PATCH);
        fs::remove_dir_all(root).expect("remove fixture");
    }

    #[test]
    fn constants_index_their_declarations_parts_in_each_version() {
        let root = fixture("constants");
        let generated = module::module(&root).expect("module");
        for text in [OLD, NEW, OTHER] {
            let schema = schema::parse(text.as_bytes()).expect("kept schema");
            for index in 0..schema.declarations() {
                let declaration = schema.declaration(DeclIx::new(index));
                let name = core::str::from_utf8(schema.spelled(declaration.name)).expect("name");
                let version =
                    generated.split(&format!("        pub mod v{} {{\n", schema.version())).nth(1).expect("version");
                let declaration = version
                    .split(&format!("            pub mod {} {{\n", name.to_ascii_lowercase()))
                    .nth(1)
                    .unwrap_or(version);
                let (first, count, kind) = match schema.declaration(DeclIx::new(index)).shape {
                    Shape::Record { first, count, .. } => (first.index(), count, "FieldIx"),
                    Shape::Enum { first, count } => (first.index(), count, "VariantIx"),
                };
                for offset in 0..count {
                    let index = first.checked_add(offset).expect("index");
                    let part = if kind == "FieldIx" {
                        schema.field(FieldIx::new(index)).name
                    } else {
                        schema.variant(VariantIx::new(index)).name
                    };
                    let name = core::str::from_utf8(schema.spelled(part)).expect("part").to_ascii_uppercase();
                    assert!(
                        declaration.contains(&format!("pub const {name}: {kind} = {kind}::new({index});")),
                        "{name}"
                    );
                }
            }
        }
        fs::remove_dir_all(root).expect("remove fixture");
    }

    #[test]
    fn current_accepts_the_written_module() {
        let root = fixture("current");
        put(&root, "patches/mod.rs", EXPECTED);
        assert_eq!(skein_codegen::patch::current(&root), Ok(()));
        fs::remove_dir_all(root).expect("remove fixture");
    }

    #[test]
    fn current_refuses_changed_and_missing_modules() {
        for (label, contents) in [("changed", Some("changed\n")), ("missing", None)] {
            let root = fixture(label);
            if let Some(contents) = contents {
                put(&root, "patches/mod.rs", contents);
            }
            assert_eq!(module::current(&root), Err(Error::Stale), "{label}");
            fs::remove_dir_all(root).expect("remove fixture");
        }
    }
