//! The kept names and written dispatch (codec.md, 12.3).

use alloc::collections::BTreeMap;
use core::fmt::Write;
use std::{fs, path::Path};

use skein_codec::schema::{self, DeclIx, FieldIx, Shape, VariantIx};

use super::{Error, files::Crate, text::PatchText};

/// Generates `patches/mod.rs` from an owner's kept texts and patches.
pub fn module(owner: &Path) -> Result<String, Error> {
    module_text(&Crate::read(owner)?)
}

/// Checks the owner's generated patch module.
pub fn current(owner: &Path) -> Result<(), Error> {
    let expected = module(owner)?;
    match fs::read_to_string(owner.join("patches/mod.rs")) {
        Ok(text) if text == expected => Ok(()),
        Ok(_) => Err(Error::Stale),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Err(Error::Stale),
        Err(error) => Err(Error::io(&owner.join("patches/mod.rs"), &error)),
    }
}

fn unique(names: &mut BTreeMap<String, String>, spelled: String, name: &str) -> Result<String, Error> {
    if let Some(first) = names.insert(spelled.clone(), name.to_owned()) {
        return Err(Error::Spelled { first, second: name.to_owned() });
    }
    Ok(spelled)
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for character in name.chars() {
        if character.is_ascii_uppercase() && !out.is_empty() {
            out.push('_');
        }
        out.push(if character == '.' || character == '-' { '_' } else { character.to_ascii_lowercase() });
    }
    out
}

fn ident(name: &str) -> String {
    // Rust's strict, reserved and weak keywords; a schema name can acquire one
    // when its case is lowered for a module or function.
    const KEYWORDS: &str = "as async await become box break const continue crate do dyn else enum extern false final fn for gen if impl in let loop macro macro_rules match mod move mut override priv pub ref return self Self static struct super trait true try type typeof union unsafe unsized use virtual where while yield";
    if KEYWORDS.split_whitespace().any(|word| word == name) { format!("r#{name}") } else { name.to_owned() }
}

pub(crate) fn function_names(patch: &PatchText) -> Result<Vec<String>, Error> {
    let mut names = BTreeMap::new();
    patch.sites().map(|(_, target, _)| unique(&mut names, ident(&snake(target)), target)).collect()
}

pub(crate) fn read_patch(source: &str, number: u32) -> Result<PatchText, Error> {
    PatchText::read(source).ok_or_else(|| Error::Schema {
        path: super::files::patch_path(number),
        error: "patch statements do not read (codec.md, 11.1)".into(),
    })
}

pub(crate) fn module_text(krate: &Crate) -> Result<String, Error> {
    let mut out = String::from(
        "// Generated by skein-codegen patch from the kept texts and the patches (codec.md, 12.3); do not edit.\n\nmod context;\npub use context::Context;\n",
    );
    for number in krate.skeletons.intersection(&krate.patches.keys().copied().collect()) {
        writeln!(out, "mod p{number:04};").expect("String write");
    }
    out.push_str("\nuse skein_codec::patch::{Build, Halt, Old, Site};\nuse skein_codec::value::Node;\n\n");
    text_array(
        &mut out,
        "",
        "PATCHES",
        &krate.patches.keys().map(|number| format!("{number:04}.patch")).collect::<Vec<_>>(),
    );
    out.push_str("\npub mod kept {\n");
    let mut families = BTreeMap::new();
    for (family, versions) in &krate.kept {
        let name = unique(&mut families, ident(&family.replace('-', "_")), family)?;
        writeln!(out, "    pub mod {name} {{").expect("String write");
        text_array(
            &mut out,
            "        ",
            "TEXTS",
            &versions.values().map(|text| format!("../{}", text.path.display())).collect::<Vec<_>>(),
        );
        for (version, text) in versions {
            let schema = schema::parse(text.source.as_bytes())
                .map_err(|error| Error::Schema { path: text.path.clone(), error: format!("{error:?}") })?;
            writeln!(out, "        pub mod v{version} {{").expect("String write");
            declarations(&schema, &mut out)?;
            out.push_str("        }\n");
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n\npub mod refusal {\n");
    let mut refusals = false;
    for (number, source) in &krate.patches {
        let patch = read_patch(source, *number)?;
        if patch.refusals().next().is_none() {
            continue;
        }
        refusals = true;
        writeln!(out, "    pub mod p{number:04} {{\n        use skein_codec::patch::RefusalIx;").expect("String write");
        let mut names = BTreeMap::new();
        for (index, name) in patch.refusals().enumerate() {
            let name = unique(&mut names, snake(name).to_ascii_uppercase(), name)?;
            writeln!(out, "        pub const {name}: RefusalIx = RefusalIx::new({index});").expect("String write");
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n\n");
    if !refusals {
        out = out.replace("pub mod refusal {\n}\n", "pub mod refusal {}\n");
    }
    dispatch(krate, &mut out)?;
    tests(krate, &mut out);
    Ok(out)
}

/// Arrays use the workspace's 120-column rustfmt layout, including the trailing comma only when expanded.
fn text_array(out: &mut String, indent: &str, name: &str, paths: &[String]) {
    let items = paths.iter().map(|path| format!("include_str!(\"{path}\")")).collect::<Vec<_>>();
    let prefix = format!("{indent}pub const {name}: &[&str] =");
    let array = format!("&[{}];", items.join(", "));
    let line = format!("{prefix} {array}");
    if line.len() <= 120 {
        writeln!(out, "{line}").expect("String write");
    } else if indent
        .len()
        .checked_add(4)
        .and_then(|width| width.checked_add(array.len()))
        .is_some_and(|width| width <= 120)
    {
        writeln!(out, "{prefix}\n{indent}    {array}").expect("String write");
    } else {
        writeln!(out, "{prefix} &[").expect("String write");
        for item in items {
            writeln!(out, "{indent}    {item},").expect("String write");
        }
        writeln!(out, "{indent}];").expect("String write");
    }
}

fn declarations(schema: &schema::Schema, out: &mut String) -> Result<(), Error> {
    let mut declarations = BTreeMap::new();
    for index in 0..schema.declarations() {
        let declaration = schema.declaration(DeclIx::new(index));
        let name = core::str::from_utf8(schema.spelled(declaration.name)).expect("schema name");
        let name = unique(&mut declarations, ident(&snake(name)), name)?;
        let empty = match declaration.shape {
            Shape::Record { count, .. } | Shape::Enum { count, .. } => count == 0,
        };
        if empty {
            writeln!(out, "            pub mod {name} {{}}").expect("String write");
            continue;
        }
        writeln!(out, "            pub mod {name} {{").expect("String write");
        let (kind, first, count) = match declaration.shape {
            Shape::Record { first, count, .. } => ("FieldIx", first.index(), count),
            Shape::Enum { first, count } => ("VariantIx", first.index(), count),
        };
        if count > 0 {
            writeln!(out, "                use skein_codec::schema::{kind};").expect("String write");
        }
        let mut names = BTreeMap::new();
        for offset in 0..count {
            let index = first.checked_add(offset).expect("schema index");
            let span = match declaration.shape {
                Shape::Record { .. } => schema.field(FieldIx::new(index)).name,
                Shape::Enum { .. } => schema.variant(VariantIx::new(index)).name,
            };
            let name = core::str::from_utf8(schema.spelled(span)).expect("schema name");
            let name = unique(&mut names, snake(name).to_ascii_uppercase(), name)?;
            writeln!(out, "                pub const {name}: {kind} = {kind}::new({index});").expect("String write");
        }
        out.push_str("            }\n");
    }
    Ok(())
}

fn dispatch(krate: &Crate, out: &mut String) -> Result<(), Error> {
    let mut arms = String::new();
    for (number, source) in &krate.patches {
        let functions = function_names(&read_patch(source, *number)?)?;
        if functions.is_empty() {
            continue;
        }
        writeln!(arms, "        {number} => match site.index() {{").expect("String write");
        for (index, function) in functions.iter().enumerate() {
            writeln!(arms, "            {index} => p{number:04}::{function}(old, new, at, cx),").expect("String write");
        }
        arms.push_str("            _ => Err(Halt::NoSite(site)),\n        },\n");
    }
    let prefix = if arms.is_empty() { "_" } else { "" };
    writeln!(out, "pub fn written(site: Site, {prefix}old: &Old, {prefix}new: &mut Build, {prefix}at: Node, {prefix}cx: &mut Context) -> Result<(), Halt> {{").expect("String write");
    if arms.is_empty() {
        out.push_str("    Err(Halt::NoSite(site))\n");
    } else {
        write!(out, "    match site.patch() {{\n{arms}        _ => Err(Halt::NoSite(site)),\n    }}\n")
            .expect("String write");
    }
    out.push_str("}\n");
    Ok(())
}

fn tests(krate: &Crate, out: &mut String) {
    out.push_str("\n#[cfg(test)]\nmod tests {\n    use std::path::Path;\n\n    fn owner() -> &'static Path {\n        Path::new(env!(\"CARGO_MANIFEST_DIR\"))\n    }\n\n    #[test]\n    fn current() {\n        skein_codegen::patch::current(owner()).map_err(|error| error.to_string()).expect(\"patches are current\");\n    }\n");
    for number in krate.patches.keys() {
        write!(out, "\n    #[test]\n    fn p{number:04}_goldens() {{\n        skein_codegen::patch::goldens(owner(), {number}, super::written)\n            .map_err(|error| error.to_string())\n            .expect(\"patch {number:04} goldens\");\n    }}\n").expect("String write");
    }
    out.push_str("}\n");
}

#[cfg(test)]
mod tests {
    use super::module_text;
    use crate::patch::{Error, files::Crate, text::PatchText};
    use std::{fs, path::PathBuf};

    fn fixture() -> PathBuf {
        let root = std::env::temp_dir().join(format!("skein-codegen-t2-spelled-{}", std::process::id()));
        fs::create_dir(&root).expect("unique scratch directory");
        fs::create_dir_all(root.join("schema/kept")).expect("kept directory");
        fs::write(root.join("schema/kept/a-b-v1.schema"), "family a-b 1\nrecord R { foo: u8 }\n").expect("kept text");
        root
    }
    #[test]
    fn names_spelling_one_constant_or_function_are_refused() {
        let root = fixture();
        let mut krate = Crate::read(&root).expect("crate");
        // The runtime grammar admits case distinctions that cannot name two
        // uppercase constants; module_text checks them before writing Rust.
        krate.kept.get_mut("a-b").expect("family").get_mut(&1).expect("v1").source =
            "family a-b 1\nrecord R { foo: u8 Foo: u8 }\n".into();
        assert_eq!(module_text(&krate), Err(Error::Spelled { first: "foo".into(), second: "Foo".into() }));
        let patch =
            PatchText::read("patch 1\nowner sample 1\nfamily a-b 1 to 2\nwritten EveryScore\nwritten Every.score\n")
                .expect("patch");
        assert_eq!(
            super::super::skeleton::skeleton_text(1, &patch, None),
            Err(Error::Spelled { first: "EveryScore".into(), second: "Every.score".into() })
        );
        fs::remove_dir_all(root).expect("remove fixture");
    }
}
